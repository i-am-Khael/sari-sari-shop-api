
CREATE DATABASE e-store-api;

USE e-store-api;

CREATE TABLE users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  first_name VARCHAR(50) NULL,
  last_name VARCHAR(50) NULL,
  email VARCHAR(100) NULL UNIQUE,
  address LONGTEXT NULL,
  avatar LONGTEXT NULL,
  is_verified BOOLEAN NULL DEFAULT 0,
  is_deleted BOOLEAN NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL
);


CREATE TABLE product_categories (
  id UNSIGNED BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  category VARCHAR(100) NOT NULL,
  description LONGTEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL
);


CREATE TABLE products (
  id UNSIGNED BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  product VARCHAR(100) NOT NULL,
  category VARCHAR(100) NOT NULL,
  stock INT(11) NULL DEFAULT 0,
  price DECIMAL(10,2) NULL DEFAULT 0,
  description LONGTEXT NULL,
  file_name LONGTEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL,
  FOREIGN KEY (category_id) REFERENCES product_categories(id) ON UPDATE CASCADE ON DELETE CASCADE
);
